-- Fashion marketplace: brands as data, product variants (size × color) with their own stock, styles and
-- occasions. Every step backfills existing rows first, so existing products, carts and orders stay valid.

-- ---------------------------------------------------------------------------------------------
-- Brands (were a free-text column): admins can add brands without code changes.
-- products.brand stays as a denormalised name (search vector, order snapshots, API compatibility).
-- ---------------------------------------------------------------------------------------------
CREATE TABLE brands (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(80)   NOT NULL,
    name        VARCHAR(80)   NOT NULL,
    description VARCHAR(1000) NOT NULL DEFAULT '',
    featured    BOOLEAN       NOT NULL DEFAULT FALSE,
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    sort_order  INT           NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_brands_slug UNIQUE (slug),
    CONSTRAINT uq_brands_name UNIQUE (name),
    CONSTRAINT ck_brands_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

INSERT INTO brands (slug, name)
SELECT DISTINCT trim(BOTH '-' FROM lower(regexp_replace(brand, '[^A-Za-z0-9]+', '-', 'g'))), brand FROM products;

ALTER TABLE products ADD COLUMN brand_id BIGINT REFERENCES brands (id);
UPDATE products p SET brand_id = b.id FROM brands b WHERE b.name = p.brand;
ALTER TABLE products ALTER COLUMN brand_id SET NOT NULL;
CREATE INDEX idx_products_brand_id ON products (brand_id);

-- ---------------------------------------------------------------------------------------------
-- Product merchandising fields
-- ---------------------------------------------------------------------------------------------
ALTER TABLE products
    ADD COLUMN gender           VARCHAR(10)    NOT NULL DEFAULT 'UNISEX',
    ADD COLUMN compare_at_price NUMERIC(12, 2),
    ADD COLUMN featured         BOOLEAN        NOT NULL DEFAULT FALSE,
    ADD COLUMN new_arrival      BOOLEAN        NOT NULL DEFAULT FALSE,
    ADD COLUMN trending         BOOLEAN        NOT NULL DEFAULT FALSE,
    ADD COLUMN material         VARCHAR(300),
    ADD COLUMN care             VARCHAR(500),
    ADD CONSTRAINT ck_products_gender CHECK (gender IN ('MEN', 'WOMEN', 'UNISEX')),
    -- a "was" price is only shown when it is a real reduction
    ADD CONSTRAINT ck_products_compare_at CHECK (compare_at_price IS NULL OR compare_at_price > price);

CREATE INDEX idx_products_gender ON products (gender);

-- ---------------------------------------------------------------------------------------------
-- Categories: archivable, and described for the outfit builder
--   outfit_slot: which part of an outfit the category fills (a dress fills TOP and BOTTOM)
--   size_scale:  ALPHA (XS-XXL), WAIST (numeric) or ONE_SIZE
-- ---------------------------------------------------------------------------------------------
ALTER TABLE categories
    ADD COLUMN active      BOOLEAN     NOT NULL DEFAULT TRUE,
    ADD COLUMN outfit_slot VARCHAR(12),
    ADD COLUMN size_scale  VARCHAR(10),
    ADD CONSTRAINT ck_categories_outfit_slot CHECK (outfit_slot IN ('TOP', 'BOTTOM', 'FULL', 'LAYER', 'ACCESSORY')),
    ADD CONSTRAINT ck_categories_size_scale CHECK (size_scale IN ('ALPHA', 'WAIST', 'ONE_SIZE'));

-- ---------------------------------------------------------------------------------------------
-- Variants: one row per size × color, each with its own SKU and stock.
-- color_family drives outfit color coordination (neutrals go with anything).
-- ---------------------------------------------------------------------------------------------
CREATE TABLE product_variants (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    sku          VARCHAR(48) NOT NULL,
    size         VARCHAR(12) NOT NULL,
    color        VARCHAR(40) NOT NULL,
    color_hex    VARCHAR(7),
    color_family VARCHAR(10) NOT NULL DEFAULT 'NEUTRAL',
    sort_order   INT         NOT NULL DEFAULT 0,
    active       BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_product_variants_sku UNIQUE (sku),
    CONSTRAINT uq_product_variants_option UNIQUE (product_id, size, color),
    CONSTRAINT ck_product_variants_hex CHECK (color_hex IS NULL OR color_hex ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_product_variants_family CHECK (color_family IN ('NEUTRAL', 'ACCENT', 'DENIM', 'METAL'))
);

CREATE INDEX idx_product_variants_product ON product_variants (product_id);
CREATE INDEX idx_product_variants_size ON product_variants (size);
CREATE INDEX idx_product_variants_color ON product_variants (color);

-- every existing product gets a default variant carrying its SKU
INSERT INTO product_variants (product_id, sku, size, color)
SELECT id, sku, 'One size', 'Standard' FROM products;

-- Stock moves from products to variants (same atomic conditional-UPDATE reservation, keyed by variant).
CREATE TABLE variant_stock (
    variant_id       BIGINT PRIMARY KEY REFERENCES product_variants (id) ON DELETE CASCADE,
    quantity_on_hand INT         NOT NULL CHECK (quantity_on_hand >= 0),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO variant_stock (variant_id, quantity_on_hand)
SELECT v.id, i.quantity_on_hand FROM inventory i JOIN product_variants v ON v.product_id = i.product_id;

DROP TABLE inventory;

-- Images can belong to one color of a product
ALTER TABLE product_images ADD COLUMN color VARCHAR(40);

-- ---------------------------------------------------------------------------------------------
-- Cart lines, order lines and bundle items reference the chosen variant
-- ---------------------------------------------------------------------------------------------
ALTER TABLE cart_items ADD COLUMN variant_id BIGINT REFERENCES product_variants (id) ON DELETE CASCADE;
UPDATE cart_items ci SET variant_id = v.id FROM product_variants v WHERE v.product_id = ci.product_id;
ALTER TABLE cart_items ALTER COLUMN variant_id SET NOT NULL;
ALTER TABLE cart_items DROP CONSTRAINT uq_cart_items_cart_product;
ALTER TABLE cart_items ADD CONSTRAINT uq_cart_items_cart_variant UNIQUE (cart_id, variant_id);

-- order history keeps what was bought: variant reference plus a size/color snapshot
ALTER TABLE order_items
    ADD COLUMN variant_id BIGINT REFERENCES product_variants (id),
    ADD COLUMN size       VARCHAR(12),
    ADD COLUMN color      VARCHAR(40);
UPDATE order_items oi SET variant_id = v.id FROM product_variants v WHERE v.product_id = oi.product_id;

ALTER TABLE bundle_items ADD COLUMN variant_id BIGINT REFERENCES product_variants (id) ON DELETE SET NULL;

-- ---------------------------------------------------------------------------------------------
-- Styles and occasions (admin-managed vocabularies used by filters and the outfit builder)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE styles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(40)  NOT NULL,
    name        VARCHAR(60)  NOT NULL,
    description VARCHAR(300) NOT NULL DEFAULT '',
    sort_order  INT          NOT NULL DEFAULT 0,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_styles_slug UNIQUE (slug)
);

CREATE TABLE occasions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(40)  NOT NULL,
    name        VARCHAR(60)  NOT NULL,
    description VARCHAR(300) NOT NULL DEFAULT '',
    sort_order  INT          NOT NULL DEFAULT 0,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_occasions_slug UNIQUE (slug)
);

CREATE TABLE product_styles (
    product_id BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    style_id   BIGINT NOT NULL REFERENCES styles (id) ON DELETE CASCADE,
    PRIMARY KEY (product_id, style_id)
);

CREATE TABLE product_occasions (
    product_id  BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    occasion_id BIGINT NOT NULL REFERENCES occasions (id) ON DELETE CASCADE,
    PRIMARY KEY (product_id, occasion_id)
);

CREATE INDEX idx_product_styles_style ON product_styles (style_id);
CREATE INDEX idx_product_occasions_occasion ON product_occasions (occasion_id);
