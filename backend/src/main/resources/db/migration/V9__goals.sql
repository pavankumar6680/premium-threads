-- Goals module: goal templates (store configuration) and customers' shopping goals.

CREATE TABLE goal_templates (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug           VARCHAR(60)    NOT NULL,
    title          VARCHAR(120)   NOT NULL,
    tagline        VARCHAR(200)   NOT NULL,
    description    TEXT           NOT NULL DEFAULT '',
    default_budget NUMERIC(12, 2) NOT NULL CHECK (default_budget > 0),
    sort_order     INT            NOT NULL DEFAULT 0,
    active         BOOLEAN        NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_goal_templates_slug UNIQUE (slug)
);

CREATE TABLE goal_template_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id         BIGINT       NOT NULL REFERENCES goal_templates (id) ON DELETE CASCADE,
    category_id         BIGINT       NOT NULL REFERENCES categories (id),
    required            BOOLEAN      NOT NULL,
    selected_by_default BOOLEAN      NOT NULL DEFAULT TRUE,
    quantity            INT          NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 10),
    note                VARCHAR(200),
    sort_order          INT          NOT NULL DEFAULT 0,
    CONSTRAINT uq_goal_template_items UNIQUE (template_id, category_id),
    CONSTRAINT ck_goal_template_items_required_selected CHECK (NOT required OR selected_by_default)
);

-- Usage choices offered in the wizard; each maps to a product tag used for relevance scoring.
CREATE TABLE goal_template_usage_options (
    template_id BIGINT      NOT NULL REFERENCES goal_templates (id) ON DELETE CASCADE,
    tag         VARCHAR(40) NOT NULL,
    label       VARCHAR(80) NOT NULL,
    sort_order  INT         NOT NULL DEFAULT 0,
    PRIMARY KEY (template_id, tag)
);

-- Phrases that identify the template in a free-text goal ("work from home", "podcast"...).
CREATE TABLE goal_template_keywords (
    template_id BIGINT      NOT NULL REFERENCES goal_templates (id) ON DELETE CASCADE,
    keyword     VARCHAR(60) NOT NULL,
    PRIMARY KEY (template_id, keyword)
);

-- A goal is immutable once created; "editing" creates a new goal. Recommendations (phase 4) reference
-- a goal, so a recommendation always matches exactly the inputs it was computed for.
CREATE TABLE shopping_goals (
    id             UUID PRIMARY KEY,
    user_id        BIGINT REFERENCES users (id) ON DELETE CASCADE,
    template_id    BIGINT REFERENCES goal_templates (id),
    title          VARCHAR(120)   NOT NULL,
    raw_text       VARCHAR(2000),
    budget         NUMERIC(12, 2) NOT NULL CHECK (budget > 0),
    quality        VARCHAR(10)    NOT NULL CHECK (quality IN ('BUDGET', 'BALANCED', 'PREMIUM')),
    space_width_cm NUMERIC(7, 1) CHECK (space_width_cm > 0),
    space_depth_cm NUMERIC(7, 1) CHECK (space_depth_cm > 0),
    notes          VARCHAR(500),
    created_at     TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX idx_shopping_goals_user_created ON shopping_goals (user_id, created_at DESC);

CREATE TABLE goal_requirements (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id     UUID        NOT NULL REFERENCES shopping_goals (id) ON DELETE CASCADE,
    category_id BIGINT      NOT NULL REFERENCES categories (id),
    kind        VARCHAR(10) NOT NULL CHECK (kind IN ('REQUIRED', 'OPTIONAL', 'OWNED')),
    quantity    INT         NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 10),
    sort_order  INT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_goal_requirements UNIQUE (goal_id, category_id)
);

CREATE TABLE goal_preferred_brands (
    goal_id UUID        NOT NULL REFERENCES shopping_goals (id) ON DELETE CASCADE,
    brand   VARCHAR(80) NOT NULL,
    PRIMARY KEY (goal_id, brand)
);

CREATE TABLE goal_usage_tags (
    goal_id UUID        NOT NULL REFERENCES shopping_goals (id) ON DELETE CASCADE,
    tag     VARCHAR(40) NOT NULL,
    PRIMARY KEY (goal_id, tag)
);
