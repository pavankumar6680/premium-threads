-- Catalog module: categories, products, typed attributes (EAV), tags, images.

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT REFERENCES categories (id),
    slug        VARCHAR(80)  NOT NULL,
    name        VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    sort_order  INT          NOT NULL DEFAULT 0,
    CONSTRAINT uq_categories_slug UNIQUE (slug)
);

CREATE INDEX idx_categories_parent_id ON categories (parent_id);

CREATE TABLE products (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id   BIGINT        NOT NULL REFERENCES categories (id),
    sku           VARCHAR(40)   NOT NULL,
    slug          VARCHAR(160)  NOT NULL,
    name          VARCHAR(160)  NOT NULL,
    brand         VARCHAR(80)   NOT NULL,
    description   TEXT          NOT NULL DEFAULT '',
    price         NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    rating_avg    NUMERIC(2, 1) NOT NULL DEFAULT 0 CHECK (rating_avg BETWEEN 0 AND 5),
    rating_count  INT           NOT NULL DEFAULT 0 CHECK (rating_count >= 0),
    -- 1 = budget, 2 = mid-range, 3 = premium; used by the recommendation engine
    quality_tier  SMALLINT      NOT NULL DEFAULT 2 CHECK (quality_tier BETWEEN 1 AND 3),
    status        VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    seller_id     BIGINT,       -- reserved for the multi-seller extension
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version       BIGINT        NOT NULL DEFAULT 0,
    search_vector TSVECTOR GENERATED ALWAYS AS (
        setweight(to_tsvector('english', name), 'A') ||
        setweight(to_tsvector('english', brand), 'A') ||
        setweight(to_tsvector('english', description), 'C')
    ) STORED,
    CONSTRAINT uq_products_sku UNIQUE (sku),
    CONSTRAINT uq_products_slug UNIQUE (slug)
);

CREATE INDEX idx_products_category_id ON products (category_id);
CREATE INDEX idx_products_brand ON products (brand);
CREATE INDEX idx_products_price ON products (price);
CREATE INDEX idx_products_search ON products USING GIN (search_vector);

CREATE TABLE product_images (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    url        VARCHAR(500) NOT NULL,
    alt_text   VARCHAR(200),
    sort_order INT          NOT NULL DEFAULT 0
);

CREATE INDEX idx_product_images_product_id ON product_images (product_id);

CREATE TABLE attribute_definitions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT      NOT NULL REFERENCES categories (id),
    key         VARCHAR(60) NOT NULL,
    label       VARCHAR(80) NOT NULL,
    data_type   VARCHAR(10) NOT NULL CHECK (data_type IN ('TEXT', 'NUMBER', 'BOOL', 'LIST')),
    unit        VARCHAR(20),
    filterable  BOOLEAN     NOT NULL DEFAULT TRUE,
    sort_order  INT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_attribute_definitions_category_key UNIQUE (category_id, key)
);

-- One row per value; LIST attributes have one row per list element.
CREATE TABLE product_attributes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    attribute_id BIGINT NOT NULL REFERENCES attribute_definitions (id),
    value_text   VARCHAR(200),
    value_number NUMERIC(12, 3),
    value_bool   BOOLEAN,
    CONSTRAINT ck_product_attributes_one_value CHECK (num_nonnulls(value_text, value_number, value_bool) = 1)
);

CREATE INDEX idx_product_attributes_product_id ON product_attributes (product_id);
CREATE INDEX idx_product_attributes_text ON product_attributes (attribute_id, value_text);
CREATE INDEX idx_product_attributes_number ON product_attributes (attribute_id, value_number);

CREATE TABLE product_tags (
    product_id BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    tag        VARCHAR(40) NOT NULL,
    PRIMARY KEY (product_id, tag)
);

CREATE INDEX idx_product_tags_tag ON product_tags (tag);
