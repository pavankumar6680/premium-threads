-- The product tag that marks products made for a template's purpose (e.g. "gaming"); used for relevance.
ALTER TABLE goal_templates ADD COLUMN context_tag VARCHAR(40);

-- Compatibility rules are data, evaluated by one strategy per operator, so new rules need no code changes.
--   EQUALS                    any source value equals a target value      (lens mount = camera mount)
--   LIST_CONTAINS             target list contains every source value      (card format in camera slots)
--   LIST_INTERSECTS           source and target lists share a value        (monitor inputs ∩ PC outputs)
--   LTE                       source number <= target number               (monitor weight <= arm load)
--   LTE_SPACE_WIDTH / _DEPTH  source number <= the customer's space        (desk width <= room width)
--   REQUIRES_CATEGORY_UNLESS  unless source list contains rule_value, the bundle needs a target-category product
--                             (an XLR-only microphone needs an audio interface)
CREATE TABLE compatibility_rules (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(60)  NOT NULL,
    source_category_id BIGINT       NOT NULL REFERENCES categories (id),
    target_category_id BIGINT REFERENCES categories (id),
    operator           VARCHAR(30)  NOT NULL CHECK (operator IN ('EQUALS', 'LIST_CONTAINS', 'LIST_INTERSECTS', 'LTE',
                                                                  'LTE_SPACE_WIDTH', 'LTE_SPACE_DEPTH',
                                                                  'REQUIRES_CATEGORY_UNLESS')),
    source_attr        VARCHAR(60)  NOT NULL,
    target_attr        VARCHAR(60),
    rule_value         VARCHAR(60),
    severity           VARCHAR(10)  NOT NULL DEFAULT 'BLOCK' CHECK (severity IN ('BLOCK', 'WARN')),
    label              VARCHAR(120) NOT NULL,
    message            VARCHAR(300) NOT NULL,
    active             BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_compatibility_rules_code UNIQUE (code),
    CONSTRAINT ck_compatibility_rules_shape CHECK (
        (operator IN ('EQUALS', 'LIST_CONTAINS', 'LIST_INTERSECTS', 'LTE')
            AND target_category_id IS NOT NULL AND target_attr IS NOT NULL)
        OR (operator IN ('LTE_SPACE_WIDTH', 'LTE_SPACE_DEPTH') AND target_category_id IS NULL)
        OR (operator = 'REQUIRES_CATEGORY_UNLESS' AND target_category_id IS NOT NULL AND rule_value IS NOT NULL))
);

CREATE INDEX idx_compatibility_rules_source ON compatibility_rules (source_category_id);
CREATE INDEX idx_compatibility_rules_target ON compatibility_rules (target_category_id);

-- One execution of the recommendation engine for a goal (goals are immutable, so a run is reproducible).
CREATE TABLE recommendation_runs (
    id                UUID PRIMARY KEY,
    goal_id           UUID           NOT NULL REFERENCES shopping_goals (id) ON DELETE CASCADE,
    algorithm_version VARCHAR(20)    NOT NULL,
    status            VARCHAR(12)    NOT NULL CHECK (status IN ('OK', 'INFEASIBLE')),
    budget            NUMERIC(12, 2) NOT NULL,
    min_feasible_cost NUMERIC(12, 2),
    nodes_explored    BIGINT         NOT NULL,
    duration_ms       INT            NOT NULL,
    complete          BOOLEAN        NOT NULL,
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX idx_recommendation_runs_goal ON recommendation_runs (goal_id, created_at DESC);

CREATE TABLE recommendation_run_messages (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id   UUID         NOT NULL REFERENCES recommendation_runs (id) ON DELETE CASCADE,
    kind     VARCHAR(12)  NOT NULL CHECK (kind IN ('NOTE', 'REASON', 'SUGGESTION')),
    message  VARCHAR(500) NOT NULL,
    position INT          NOT NULL
);

CREATE INDEX idx_recommendation_run_messages_run ON recommendation_run_messages (run_id);

CREATE TABLE bundles (
    id          UUID PRIMARY KEY,
    goal_id     UUID           NOT NULL REFERENCES shopping_goals (id) ON DELETE CASCADE,
    run_id      UUID REFERENCES recommendation_runs (id) ON DELETE SET NULL,
    user_id     BIGINT REFERENCES users (id) ON DELETE CASCADE,
    tier        VARCHAR(10)    NOT NULL CHECK (tier IN ('BUDGET', 'BALANCED', 'PREMIUM', 'CUSTOM')),
    name        VARCHAR(120)   NOT NULL,
    status      VARCHAR(12)    NOT NULL CHECK (status IN ('RECOMMENDED', 'SAVED')),
    budget      NUMERIC(12, 2) NOT NULL CHECK (budget > 0),
    total_price NUMERIC(12, 2) NOT NULL CHECK (total_price >= 0),
    score       NUMERIC(10, 4),
    summary     VARCHAR(500),
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    version     BIGINT         NOT NULL DEFAULT 0
);

CREATE INDEX idx_bundles_run ON bundles (run_id);
CREATE INDEX idx_bundles_user_status ON bundles (user_id, status);

-- unit_price is the price when the bundle was recommended; views also show the live price.
CREATE TABLE bundle_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_id   UUID           NOT NULL REFERENCES bundles (id) ON DELETE CASCADE,
    product_id  BIGINT         NOT NULL REFERENCES products (id),
    category_id BIGINT         NOT NULL REFERENCES categories (id),
    quantity    INT            NOT NULL CHECK (quantity BETWEEN 1 AND 10),
    unit_price  NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    optional    BOOLEAN        NOT NULL DEFAULT FALSE,
    locked      BOOLEAN        NOT NULL DEFAULT FALSE,
    explanation VARCHAR(1000),
    sort_order  INT            NOT NULL DEFAULT 0,
    CONSTRAINT uq_bundle_items_category UNIQUE (bundle_id, category_id)
);

CREATE INDEX idx_bundle_items_bundle ON bundle_items (bundle_id);
