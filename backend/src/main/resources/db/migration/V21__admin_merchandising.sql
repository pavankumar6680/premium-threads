-- Admin merchandising: uploaded product images and the homepage's product rails.

-- Images uploaded through the admin are stored on local disk and served under /media; stored_name is the
-- file's path inside the media directory (NULL for images that live elsewhere, e.g. seeded editorial art).
ALTER TABLE product_images ADD COLUMN stored_name VARCHAR(200);
ALTER TABLE product_images ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT now();

-- Product rails on the homepage. Built-in rails (trending, new-arrivals, offers, recommended) have fixed places
-- in the layout; any other row is an extra collection shown after them. query is a catalog filter, e.g.
-- "flag=trending" or "style=streetwear&gender=WOMEN".
CREATE TABLE home_sections (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       VARCHAR(40)  NOT NULL,
    eyebrow    VARCHAR(60)  NOT NULL DEFAULT '',
    title      VARCHAR(80)  NOT NULL,
    query      VARCHAR(300) NOT NULL,
    position   INT          NOT NULL DEFAULT 0,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_home_sections_slug UNIQUE (slug)
);

