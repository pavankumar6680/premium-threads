-- Phase 7: administration.

-- Every change made through the admin API is recorded: who, what, when, and a JSON summary of the change.
CREATE TABLE admin_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    actor_email VARCHAR(254) NOT NULL,
    action      VARCHAR(40)  NOT NULL,
    entity_type VARCHAR(40)  NOT NULL,
    entity_id   VARCHAR(60)  NOT NULL,
    details     JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_admin_audit_log_created ON admin_audit_log (created_at DESC);
CREATE INDEX idx_admin_audit_log_entity ON admin_audit_log (entity_type, entity_id);

-- Admin order list filters by status and sorts by date; analytics aggregates by date.
CREATE INDEX idx_orders_status_created ON orders (status, created_at DESC);
CREATE INDEX idx_orders_created ON orders (created_at DESC);
CREATE INDEX idx_shopping_goals_created ON shopping_goals (created_at DESC);
CREATE INDEX idx_recommendation_runs_created ON recommendation_runs (created_at DESC);
