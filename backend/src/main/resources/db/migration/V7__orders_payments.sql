-- Orders and payments modules. Order items snapshot product name/SKU/price at purchase time, and the
-- shipping address is copied onto the order, so history never changes when the catalog or address book does.

CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number     VARCHAR(20)    NOT NULL,
    user_id          BIGINT         NOT NULL REFERENCES users (id),
    status           VARCHAR(20)    NOT NULL CHECK (status IN ('PAID', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    subtotal         NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),
    shipping         NUMERIC(12, 2) NOT NULL CHECK (shipping >= 0),
    tax              NUMERIC(12, 2) NOT NULL CHECK (tax >= 0),
    total            NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
    currency         VARCHAR(3)     NOT NULL DEFAULT 'USD',
    ship_full_name   VARCHAR(120)   NOT NULL,
    ship_line1       VARCHAR(200)   NOT NULL,
    ship_line2       VARCHAR(200),
    ship_city        VARCHAR(100)   NOT NULL,
    ship_state       VARCHAR(100)   NOT NULL,
    ship_postal_code VARCHAR(20)    NOT NULL,
    ship_country     VARCHAR(2)     NOT NULL,
    ship_phone       VARCHAR(30),
    idempotency_key  VARCHAR(64)    NOT NULL,
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    cancelled_at     TIMESTAMPTZ,
    version          BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_orders_order_number UNIQUE (order_number),
    -- a retried checkout with the same key returns the original order instead of creating a duplicate
    CONSTRAINT uq_orders_user_idempotency_key UNIQUE (user_id, idempotency_key)
);

CREATE INDEX idx_orders_user_created ON orders (user_id, created_at DESC);

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id   BIGINT         NOT NULL REFERENCES products (id),
    sku          VARCHAR(40)    NOT NULL,
    product_name VARCHAR(160)   NOT NULL,
    brand        VARCHAR(80)    NOT NULL,
    unit_price   NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    quantity     INT            NOT NULL CHECK (quantity > 0),
    line_total   NUMERIC(12, 2) NOT NULL CHECK (line_total >= 0)
);

CREATE INDEX idx_order_items_order_id ON order_items (order_id);

CREATE TABLE payments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL REFERENCES orders (id),
    amount     NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
    method     VARCHAR(30)    NOT NULL,
    status     VARCHAR(20)    NOT NULL CHECK (status IN ('APPROVED', 'REFUNDED')),
    reference  VARCHAR(40)    NOT NULL,
    created_at TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uq_payments_order_id UNIQUE (order_id),
    CONSTRAINT uq_payments_reference UNIQUE (reference)
);
